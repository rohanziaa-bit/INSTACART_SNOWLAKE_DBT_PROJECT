DESCRIBE TABLE INS_DB.STAGING_BRONZE.BR_PRODUCT;

SELECT
    PRODUCT_ID,
    COUNT(*) AS TOTAL_ROWS
FROM INS_DB.STAGING_BRONZE.BR_PRODUCT
GROUP BY PRODUCT_ID
HAVING COUNT(*) > 1;

SELECT COUNT(*) AS NULL_PRODUCT_IDS
FROM INS_DB.STAGING_BRONZE.BR_PRODUCT
WHERE PRODUCT_ID IS NULL;

SELECT COUNT(*) AS INVALID_PRODUCT_NAMES
FROM INS_DB.STAGING_BRONZE.BR_PRODUCT
WHERE PRODUCT_NAME IS NULL
OR TRIM(PRODUCT_NAME) = '';

SELECT COUNT(*) AS NULL_AISLE_IDS
FROM INS_DB.STAGING_BRONZE.BR_PRODUCT
WHERE AISLE_ID IS NULL;

SELECT COUNT(*) AS NULL_DEPARTMENT_IDS
FROM INS_DB.STAGING_BRONZE.BR_PRODUCT
WHERE DEPARTMENT_ID IS NULL;

SELECT COUNT(*) AS INVALID_AISLE_IDS
FROM INS_DB.STAGING_BRONZE.BR_PRODUCT p
LEFT JOIN INS_DB.STAGING_BRONZE.BR_AISLE a
    ON p.AISLE_ID = a.AISLE_ID
WHERE a.AISLE_ID IS NULL;

select count(*) as invalid_deparmtent_ids
from INS_DB.STAGING_BRONZE.BR_PRODUCT AS p
left join INS_DB.STAGING_BRONZE.BR_DEPARTMENT AS d
     on p.department_id = d.department_id
where d.department_id is null;

