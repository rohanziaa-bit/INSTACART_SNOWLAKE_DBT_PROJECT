-- 1. AISLES
CREATE TABLE IF NOT EXISTS AISLES (
    AISLE_ID NUMBER,
    AISLE VARCHAR(255)
);

-- 2. DEPARTMENTS
CREATE TABLE IF NOT EXISTS DEPARTMENTS (
    DEPARTMENT_ID NUMBER,
    DEPARTMENT VARCHAR(255)
);

-- 3. PRODUCTS
CREATE TABLE IF NOT EXISTS PRODUCTS (
    PRODUCT_ID NUMBER,
    PRODUCT_NAME VARCHAR(500),
    AISLE_ID NUMBER,
    DEPARTMENT_ID NUMBER
);

-- 4. ORDERS
CREATE TABLE IF NOT EXISTS ORDERS (
    ORDER_ID NUMBER,
    USER_ID NUMBER,
    EVAL_SET VARCHAR(50),
    ORDER_NUMBER NUMBER,
    ORDER_DOW NUMBER,
    ORDER_HOUR_OF_DAY NUMBER,
    DAYS_SINCE_PRIOR_ORDER FLOAT
);

-- 5. ORDER_PRODUCTS_PRIOR
CREATE TABLE IF NOT EXISTS ORDER_PRODUCTS_PRIOR (
    ORDER_ID NUMBER,
    PRODUCT_ID NUMBER,
    ADD_TO_CART_ORDER NUMBER,
    REORDERED NUMBER
);

