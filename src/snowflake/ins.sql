FROM INS_DB.STAGING_BRONZE.BR_ORDER
ORDER BY EVAL_SET;

SELECT COUNT(*) AS INVALID_EVAL_SET
FROM INS_DB.STAGING_BRONZE.BR_ORDER
WHERE LOWER(EVAL_SET) NOT IN ('prior', 'train', 'test')
   OR EVAL_SET IS NULL;

SELECT COUNT(*) AS NULL_ORDER_NUMBER
FROM INS_DB.STAGING_BRONZE.BR_ORDER
WHERE ORDER_NUMBER IS NULL;

SELECT COUNT(*) AS INVALID_ORDER_NUMBER
FROM INS_DB.STAGING_BRONZE.BR_ORDER
WHERE ORDER_NUMBER <= 0;

SELECT COUNT(*) AS INVALID_ORDER_DOW
FROM INS_DB.STAGING_BRONZE.BR_ORDER
WHERE ORDER_DOW NOT BETWEEN 0 AND 6
   OR ORDER_DOW IS NULL;


SELECT COUNT(*) AS INVALID_ORDER_HOUR
FROM INS_DB.STAGING_BRONZE.BR_ORDER
WHERE ORDER_HOUR_OF_DAY NOT BETWEEN 0 AND 23
   OR ORDER_HOUR_OF_DAY IS NULL;

   SELECT COUNT(*) AS NULL_DAYS_SINCE_PRIOR
